# -*- coding: utf-8 -*-
"""配色主题 (从 主窗口.py 抽出, 2026-09-17)

为什么单独一个模块: 缓存面板 / 模型管理面板 / 训练器面板 都要用 Theme,
而它们是被 主窗口.py 导入的 —— 如果它们反过来 from 主窗口 import Theme,
就形成循环导入 (靠 import 顺序侥幸成立, 顺序一变就崩)。主题是纯常量, 独立最干净。
"""


# ==================== 主题配色 ====================
class Theme:
    """配色主题 —— 由参考图《汐》取色后做**实用化**改造 (2026-09-17)

    参考图实测特征: 明度均值 0.967、97.6% 像素 V>0.85、饱和度均值 0.135、
    86.7% 的色相落在 210~270°(蓝→紫蓝)。那套配色"仙"在**极低对比**上,
    直接搬进数据分析工具会看不清数字 —— 实测参考图的次要文字色 #8A87A8 在白底上
    对比度只有 3.44:1 (正文标准 4.5:1), 主色 #8E93D8 配白字更是只有 2.87:1。

    所以取"神"不取"色", 分三级落地:
      1. 色相族照搬: 长春花蓝为主, 紫蓝做阶, 暖金/蜜桃粉做点缀 (替代刺眼的纯红);
      2. 浅紫蓝**只用于容器与装饰** (背景/面板/次层/边框/页签底), 那里不承载小字;
      3. 承载文字与图形的地方**加深到通过对比度**: 正文 #3B3A56 (白底 10.9:1)、
         次要文字 #5A5775 (6.9:1)、主按钮 #5B60A8 配白字 (5.7:1)、
         图表主色 #4A4E8F (白底 7.6:1, 散点/柱状在浅底上也够清楚)。

    ⚠ 改这些值前先算对比度 (WCAG 相对明度公式, 见 自检.py 的「主题对比度」一项):
      正文需 >=4.5, 大字/非文本 >=3.0。改完跑一次包内自检就会拦住不合规的调色。
    """
    # ---- 容器层 (浅, 不承载小字) ----
    BG = "#F7F6FC"          # 窗口背景: 最浅冷紫白
    PANEL = "#FFFFFF"       # 面板/卡片
    PANEL_ALT = "#EFEDFA"   # 面板次层 (淡薰衣草): 表头、未选中页签、输入框底
    BORDER = "#DAD6EE"      # 边框/分割线: 淡紫, 比原来的灰 #dfe3e8 更柔和统一
    BAR_BG = "#E9E7F6"      # 进度条槽/装饰条底

    # ---- 主体色 (深, 承载文字与图形) ----
    ACCENT = "#5B60A8"        # 主色: 主按钮底、菜单选中底 (配白字 5.7:1)
    ACCENT_HOVER = "#4A4E8F"  # 悬停: 加深 (浅色悬停会掉对比度)
    ACCENT_PRESS = "#3F4380"  # 按下
    ACCENT_TEXT = "#4A4E8F"   # 主色**文字** (白底 7.6:1): 标题、加粗标签
    ACCENT_LIGHT = "#A9ADF2"  # 亮紫蓝: 只做装饰/描边/图表高亮 (非文本)
    ACCENT_SOFT = "#EFEDFA"   # 淡紫底: 高亮行的底

    # ---- 文字层 ----
    TEXT = "#3B3A56"        # 正文 (白底 10.9:1) —— 直接取自参考图的深蓝灰
    MUTED = "#5A5775"       # 次要文字 (6.9:1); 不用参考图的 #8A87A8 (仅 3.44:1)
    DISABLED = "#8A87A0"    # 禁用文字 (白底 3.47 / 淡紫底 3.00, 仅用于禁用态)

    # ---- 语义色 (按参考图的暖点缀调整: 蜜桃粉/薄荷青, 替代刺眼纯红纯绿) ----
    SUCCESS = "#3E9E8F"     # 薄荷青加深 (白底 3.9:1, 可用于文字与图形)
    DANGER = "#B04A5E"      # 蜜桃玫瑰加深 (白字 5.27:1, 可做按钮底)
    DANGER_HOVER = "#9E4256"
    WARN = "#C08A3E"        # 淡金加深 (白底 3.5:1)
    WARN_SOFT = "#F2D9A0"   # 参考图的淡金原色, 只做装饰

    FONT = ("Microsoft YaHei UI", 9)
    FONT_BOLD = ("Microsoft YaHei UI", 9, "bold")
    FONT_TITLE = ("Microsoft YaHei UI", 10, "bold")

    # ---- 数据可视化色图 (3D 状态图的节点按 BFS 深度着色) ----
    # 原来用 matplotlib 默认的 viridis (深紫→青→黄), 在紫蓝主题里显得突兀。
    # 换成同色系单色阶, 但**必须保住 viridis 的两个科学性**:
    #   1. 相对明度严格单调 (实测 0.066 → 0.927, 跨度 0.861; viridis 约 0.89)
    #      —— 明度单调意味着即使完全色盲, 也能靠亮度区分深度;
    #   2. 全部落在"紫蓝"一个色相族内, 不会出现彩虹式的假边界。
    # 改这些值前请重算相对明度是否仍然单调 (自检.py 的「主题对比度」会检查单调性)。
    深度色阶 = ('#3F4380', '#5B60A8', '#8B86E2', '#A9ADF2',
               '#C3C2F3', '#E4E5FA', '#F7F6FC')

    @staticmethod
    def 深度色图():
        """按 深度色阶 构建 matplotlib 线性色图 (懒构建 + 缓存, 避免导入 matplotlib)"""
        global _深度色图缓存
        if _深度色图缓存 is None:
            from matplotlib.colors import LinearSegmentedColormap
            _深度色图缓存 = LinearSegmentedColormap.from_list('hrd_depth', Theme.深度色阶)
        return _深度色图缓存


_深度色图缓存 = None
